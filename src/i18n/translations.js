/**
 * Robust translation resolver with multi-language fallback and bidirectional aliases
 */
export const t = (lang, key, fallback = '') => {
  if (!key) return '';
  const currentLang = translations[lang] ? lang : 'en';
  const dict = translations[currentLang] || {};
  const enDict = translations.en || {};

  // 1. Direct key match in active language
  if (dict[key] !== undefined && dict[key] !== '') {
    return dict[key];
  }

  // 2. Check alias mappings (camelCase -> dot notation / literal)
  if (ALIAS_MAPPINGS[key]) {
    for (const alt of ALIAS_MAPPINGS[key]) {
      if (dict[alt] !== undefined && dict[alt] !== '') return dict[alt];
    }
  }

  // 3. Check reverse alias mappings (dot notation / literal -> camelCase)
  for (const [primaryKey, aliases] of Object.entries(ALIAS_MAPPINGS)) {
    if (aliases.includes(key)) {
      if (dict[primaryKey] !== undefined && dict[primaryKey] !== '') return dict[primaryKey];
      for (const sibling of aliases) {
        if (dict[sibling] !== undefined && dict[sibling] !== '') return dict[sibling];
      }
    }
  }

  // 4. Fallback to English dictionary
  if (enDict[key] !== undefined && enDict[key] !== '') {
    return enDict[key];
  }

  if (ALIAS_MAPPINGS[key]) {
    for (const alt of ALIAS_MAPPINGS[key]) {
      if (enDict[alt] !== undefined && enDict[alt] !== '') return enDict[alt];
    }
  }

  return fallback || key;
};

export default translations;
